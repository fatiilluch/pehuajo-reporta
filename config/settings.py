def _get_or_create_development_secret_key(path):
    try:
        secret_key = path.read_text(encoding="utf-8").strip()
    except FileNotFoundError:
        secret_key = get_random_secret_key()
        try:
            file_descriptor = os.open(
                path,
                os.O_CREAT | os.O_EXCL | os.O_WRONLY,
                0o600,
            )
        except FileExistsError:
            secret_key = path.read_text(encoding="utf-8").strip()
        else:
            with os.fdopen(file_descriptor, "w", encoding="utf-8") as secret_file:
                secret_file.write(secret_key)

    if not secret_key:
        raise ImproperlyConfigured("The local Django secret key file is empty.")
    return secret_key


